export type ActivityText = keyof typeof filipino;

export function getActivityText(value: unknown) {
  const language = normalizeActivityLanguage(value);
  function t(key: ActivityText, values: Record<string, string | number> = {}): string {
    const template = language === "fil" ? filipino[key] : key;
    return template.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
  }
  /** Only call for interface/transport messages, never teacher-authored content. */
  function message(value: unknown, fallback: ActivityText): string {
    const raw = value instanceof Error ? value.message : typeof value === "string" ? value : "";
    if (language === "en") return raw || fallback;
    if (Object.prototype.hasOwnProperty.call(filipino, raw)) return t(raw as ActivityText);
    if (value && typeof value === "object" && "code" in value && value.code === "NO_SPEECH") {
      return t("No speech could be recognized from the recording.");
    }
    // Unknown server/provider detail must not leak English into a Filipino screen.
    return t(fallback);
  }
  return { language, t, message };
}
