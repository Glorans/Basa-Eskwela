/** Presentation only. Never use this helper to configure speech or calculate scores. */
export type ActivityLanguage = "en" | "fil";

export function normalizeActivityLanguage(value: unknown): ActivityLanguage {
  return typeof value === "string" && ["filipino", "tagalog", "fil", "fil-ph", "tl", "tl-ph"].includes(value.trim().toLowerCase())
    ? "fil" : "en";
}

// Router state carries the source metadata through loading/error screens, including
// browser back/forward and refresh. Each destination's saved metadata takes priority.
export function activityLanguageState(language: unknown) {
  return { readingActivityLanguage: normalizeActivityLanguage(language) };
}

export function activityLanguageFromState(state: unknown): unknown {
  return state && typeof state === "object" && "readingActivityLanguage" in state
    ? state.readingActivityLanguage : undefined;
}

